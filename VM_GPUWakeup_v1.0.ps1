Write-Host '   - 已用 Host_Master 把 NVIDIA 驅動搬進 VM' -ForegroundColor Gray
Write-Host '   - 有時開機後 OpenGL 程式能跑,有時跳 GDI Generic' -ForegroundColor Gray
