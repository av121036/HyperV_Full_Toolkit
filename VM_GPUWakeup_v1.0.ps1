# =========================================================
#  VM_GPUWakeup_v1.2.ps1  -  GPU partition 開機喚醒
#                           + registry self-heal
#                           + fallback ICD 註冊路徑全寫
#                           (在 VM 內部執行,不在主機跑)
#
#  v1.2 (新增 fallback ICD 路徑 + FeatureScore boost)
#    Windows OpenGL ICD 查詢路徑不只 Display Class subkey,還有:
#      a) HKLM\SOFTWARE\Microsoft\Windows NT\CurrentVersion\OpenGLDrivers
#         (舊式 ICD 註冊,Java OpenGL / 某些跨平台 loader 會查)
#      b) HKLM\SOFTWARE\WOW6432Node\...\OpenGLDrivers (32-bit fallback)
#      c) HKLM\SOFTWARE\Khronos\OpenGL\Drivers (Khronos-style loader)
#    v1.2 把這 3 個路徑都註冊到當前 nvoglv64.dll,並把 vrd.inf
#    (NVIDIA partition) 的 FeatureScore 拉高、wvmbusvideo (Hyper-V
#    Video) 的 FeatureScore 壓低,試著影響 Windows 主螢幕選擇邏輯。
#    這些都是「純 registry,不裝 VDD / Parsec / Mesa」的最後招式。
#
#  v1.1 (新增 self-heal)
#    主機 NVIDIA driver 升級後,VM 內 HostDriverStore 的
#    nv*.inf_amd64_* 資料夾名字會跟著改 hash:
#       nvmdsi.inf_amd64_549a... (591.74)
#       nvmdi.inf_amd64_41c61b... (596.36)
#       nv_dispi.inf_amd64_67995ce... (更新版)
#    每次 hash 變,registry 內的 OpenGLDriverName 路徑就過期 → GDI Generic
#    v1.1 在每次開機 wakeup 時自動偵測「現在哪個 nv*.inf 資料夾真的有
#    nvoglv64.dll」,把所有 Display Class subkey 內的路徑更新到該位置,
#    順便也修 Khronos Vulkan ICD 註冊。Driver 升級無痛。
#
#  v1.0
#    解決 Hyper-V GPU-PV 場景下「有時 OpenGL 程式打得開,
#    有時打不開」的競態問題:
#
#    開機時若 opengl32.dll 在 NVIDIA driver 完整 init 之前就被
#    第一次查 ICD,結果會 cache 成 GDI Generic;之後就算 NVIDIA
#    醒了,opengl32 還是給 GDI Generic 一直到下次重開機。
#
#    解法:VM 開機自動先做以下動作,把 GPU 完整喚醒,讓 opengl32
#    第一次查到的就是 NVIDIA ICD:
#      1. 等 NVIDIA Display 裝置 PnP 狀態變 OK
#      1.5 (v1.1) 自動修正 registry 內的 OpenGL/UMD/Vulkan 路徑
#      2. 跑 vulkaninfo --summary 觸發 Vulkan init
#      3. 跑 dxdiag /t 觸發 D3D init
#      4. 用 P/Invoke 建一個 OpenGL context 強制 cache NVIDIA ICD
#
#  此工具會:
#    - 在 C:\GPU_Wakeup.ps1 寫一份開機腳本
#    - 建立 SYSTEM 排程「GPU_Wakeup」(AtStartup 觸發)
#    - 立即跑一次,輸出 log 給你看現在狀態
#
#  Log 位置:C:\GPU_Wakeup.log
# =========================================================

